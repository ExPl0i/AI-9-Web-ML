    #    - значение не из допустимых: "допустимые значения: " + ", ".join(allowed);
    #    - иначе features[имя] = value.
    # 4. Каждая ошибка – словарь {"field": имя, "error": текст}. Не останавливайтесь на первой ошибке.
    # 5. Если ошибки есть, верните (None, errors), иначе (features, []).
